// Bundles the slot audio render worker into a plain static script. Turbopack cannot compile the
// `new Worker(new URL(...))` entry in production (it ships the raw .ts file), so the worker is built here
// and served from /workers/. Runs before `next dev` and `next build`.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(web, 'public/workers/slot-audio-render.js');

// Runs BEFORE the worker bundle: that bundle resolves voice-version.generated.ts (via win-tiers), which must exist.
// Voice lines (/audio/voice/<game>/<tr|en>/<stem>.mp3) keep stable names, so every consumer appends ?v=<hash of that language
// folder> (lib/slot-audio/voice-version.ts) and public/_headers serves them `immutable`. The hash is derived from the sha256 of
// every file in the folder, so changing, adding or removing any file changes the URL of that game/language bank.
const voiceRoot = resolve(web, 'public/audio/voice');
const versions = {};
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
if (existsSync(voiceRoot)) {
  for (const game of readdirSync(voiceRoot, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
    for (const lang of readdirSync(resolve(voiceRoot, game), { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
      const dir = resolve(voiceRoot, game, lang);
      const files = readdirSync(dir, { withFileTypes: true }).filter(f => f.isFile() && f.name.endsWith('.mp3')).map(f => f.name).sort();
      if (!files.length) continue;
      versions[`/audio/voice/${game}/${lang}`] = sha(files.map(f => `${f}:${sha(readFileSync(resolve(dir, f)))}`).join('\n')).slice(0, 12);
    }
  }
}
const voiceManifest = resolve(web, 'lib/slot-audio/voice-version.generated.ts');
const voiceNext = `// Generated by scripts/build-audio-worker.mjs. Do not edit.\nexport const VOICE_FOLDER_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 2)};\n`;
let voicePrevious = '';
try { voicePrevious = readFileSync(voiceManifest, 'utf8'); } catch {}
if (voicePrevious !== voiceNext) writeFileSync(voiceManifest, voiceNext);
console.log(`voice versions for ${Object.keys(versions).length} folders`);

const result = await build({
  entryPoints: [resolve(web, 'lib/slot-audio/render.worker.ts')],
  bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true,
  write: false, logLevel: 'warning', legalComments: 'none',
});
const code = result.outputFiles[0].contents;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, code);
// The page loads the worker with this hash as a query string so a new build never reuses a stale copy.
const hash = createHash('sha256').update(code).digest('hex').slice(0, 12);
const manifest = resolve(web, 'lib/slot-audio/worker-version.generated.ts');
const next = `export const SLOT_AUDIO_WORKER_VERSION = '${hash}';\n`;
let previous = '';
try { previous = readFileSync(manifest, 'utf8'); } catch {}
if (previous !== next) writeFileSync(manifest, next);
console.log(`slot audio worker ${hash} (${code.length} bytes)`);
