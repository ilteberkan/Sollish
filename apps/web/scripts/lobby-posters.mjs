// Lobby key art: screenshots every [data-poster] frame of /lab/lobby-posters (composed from each game's own art
// components, see components/lobby/poster-lab.tsx) with reduced motion, encodes it as WebP and writes
// public/images/lobby/<id>-<variant>.webp plus lib/lobby/posters.generated.ts (content hash per file, used as ?v= so a
// changed poster gets a new URL). Needs a running `next dev` (the lab page is development-only).
// Usage (repo root): bash scripts/use-node.sh node apps/web/scripts/lobby-posters.mjs --base http://127.0.0.1:3031 [--out report.json]
// PW_CHROMIUM_PATH selects a Chromium binary when Playwright's bundled one is not installed.
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(web, 'package.json'));
const { chromium } = require('@playwright/test');
// sharp ships with next (image optimisation); resolve it through next so no extra dependency is needed.
const sharp = createRequire(require.resolve('next/package.json'))('sharp');

const arg = name => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : undefined; };
const base = arg('--base') ?? 'http://127.0.0.1:3000';
const out = arg('--out');
/* WebP quality per format: tiles are small on screen, the wide hero is the LCP image. */
const QUALITY = { tile: 72, wide: 70, narrow: 72, land: 74 };

const browser = await chromium.launch(process.env.PW_CHROMIUM_PATH ? { executablePath: process.env.PW_CHROMIUM_PATH } : {});
const context = await browser.newContext({ viewport: { width: 2000, height: 1400 }, deviceScaleFactor: 1, reducedMotion: 'reduce', locale: 'en-US' });
const page = await context.newPage();
await page.goto(`${base}/lab/lobby-posters`, { waitUntil: 'networkidle', timeout: 120_000 });
// Only the frames matter: hide the site chrome so nothing overlaps a frame while it is captured.
await page.addStyleTag({ content: 'header, aside, nav, .restore-chat, .skip-link, .page-footer { display: none !important } .workspace, .app-frame { display: block !important; max-width: none !important } main { padding: 0 !important }' });
await page.evaluate(() => document.fonts.ready);
await page.waitForTimeout(1500);

const dir = join(web, 'public/images/lobby');
mkdirSync(dir, { recursive: true });
const versions = {};
const report = { generatedAt: new Date().toISOString(), base, files: {} };
for (const frame of await page.locator('[data-poster]').all()) {
  const key = await frame.getAttribute('data-poster');
  const variant = key.split('-').pop();
  await frame.scrollIntoViewIfNeeded();
  await page.waitForTimeout(150);
  // Clip to whole pixels at the frame's exact size (a fractional top would add a row).
  const box = await frame.boundingBox();
  const [w, h] = await frame.evaluate(el => [el.offsetWidth, el.offsetHeight]);
  const png = await page.screenshot({ type: 'png', animations: 'disabled', clip: { x: Math.round(box.x), y: Math.round(box.y), width: w, height: h } });
  const webp = await sharp(png).webp({ quality: QUALITY[variant] ?? 72, effort: 6, smartSubsample: true }).toBuffer();
  const meta = await sharp(webp).metadata();
  writeFileSync(join(dir, `${key}.webp`), webp);
  const hash = createHash('sha256').update(webp).digest('hex');
  versions[key] = hash.slice(0, 10);
  report.files[key] = { bytes: webp.length, width: meta.width, height: meta.height, sha256: hash };
  console.log(`${key}.webp ${meta.width}x${meta.height} ${(webp.length / 1024).toFixed(1)} KiB`);
}
await browser.close();

const sorted = Object.fromEntries(Object.entries(versions).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(join(web, 'lib/lobby/posters.generated.ts'), `// Generated by scripts/lobby-posters.mjs. Do not edit.\nexport const POSTER_VERSIONS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(sorted, null, 2)});\n`);
report.totalBytes = Object.values(report.files).reduce((sum, file) => sum + file.bytes, 0);
if (out) writeFileSync(resolve(process.cwd(), out), JSON.stringify(report, null, 2) + '\n');
console.log(`total ${(report.totalBytes / 1024).toFixed(1)} KiB in ${Object.keys(report.files).length} files`);
