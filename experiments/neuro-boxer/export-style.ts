/**
 * Writes a trained neuro-2 theta as the generated, hash-pinned module packages/protocol/src/neuro-boxer-2-model.ts.
 * neuro-1's export.ts and neuro-boxer-model.ts stay untouched; the graph is re-exported from neuro-1 (same data).
 *   node --import tsx experiments/neuro-boxer/export-style.ts <runDir> [--provisional] [--note "text"]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { NEURO2_DIM, NEURO2_VERSION } from "../../packages/protocol/src/neuro-boxer-2";

const [runDir, ...flags] = process.argv.slice(2);
if (!runDir) throw new Error("usage: export-style.ts <runDir> [--provisional] [--note text]");
const provisional = flags.includes("--provisional"), note = flags.includes("--note") ? flags[flags.indexOf("--note") + 1] ?? "" : "";
const sha = (s: string | Buffer) => createHash("sha256").update(s).digest("hex");
const raw = readFileSync(`${runDir}/theta.json`, "utf8"), j = JSON.parse(raw), summary = JSON.parse(readFileSync(`${runDir}/summary.json`, "utf8"));
if (j.dim !== NEURO2_DIM || j.theta.length !== NEURO2_DIM) throw new Error(`theta dim ${j.dim} != ${NEURO2_DIM}`);
if (j.variant !== "connectome") throw new Error("only the real-connectome variant ships");
const graph = JSON.parse(readFileSync("experiments/neuro-boxer/graph.json", "utf8"));
const info = {
  version: NEURO2_VERSION, engine: summary.engine.version, engineSha256: summary.engine.combatSparringSha256, thetaSha256: sha(raw),
  graphSha256: graph.graphSha256, graphFileSha256: sha(readFileSync("experiments/neuro-boxer/graph.json")),
  training: { method: "evolution strategies (antithetic, centred ranks, Adam); stage A style-locked tactics + shaping, stage B strategist only, stage C joint", variant: j.variant, trainingSeed: j.seed, generations: summary.generations, init: summary.init, temperature: summary.temperature, validationScore: summary.validationWide?.score ?? null, note },
  recommendedTemperature: summary.temperature, provisional, source: "male-cns:v1.0", license: "CC-BY-4.0", wholeBrain: false, consciousness: false,
};
const body = `/** GENERATED by experiments/neuro-boxer/export-style.ts; do not hand-edit.
 * NeuroBoxer v2 (neuro-2): learned strategist head + style-conditioned tactical brain on the real MaleCNS v1.0
 * descending-neuron subgraph (CC BY 4.0; FlyEM/HHMI Janelia, Cambridge, MRC LMB, Google Research), graph shared
 * with neuro-1. ${provisional ? "PROVISIONAL weights (smoke/curriculum training); not the evaluated model." : "Evaluated model: see experiments/neuro-boxer/evidence-style.json."} */
import type { NeuroGraph } from "./neuro-boxer";
import { neuro2Params, type Neuro2Params } from "./neuro-boxer-2";
import { NEURO_BOXER_GRAPH } from "./neuro-boxer-model";
export const NEURO2_INFO = Object.freeze(${JSON.stringify(info)});
export const NEURO2_GRAPH: NeuroGraph = NEURO_BOXER_GRAPH;
/** ${j.variant} training seed ${j.seed}, theta.json SHA256 ${info.thetaSha256} */
export const NEURO2_PARAMS: Neuro2Params = Object.freeze(neuro2Params(Float64Array.from(${JSON.stringify(j.theta)})));
`;
writeFileSync("packages/protocol/src/neuro-boxer-2-model.ts", body);
console.log(JSON.stringify({ thetaSha256: info.thetaSha256, provisional, engine: info.engine, engineSha256: info.engineSha256, bytes: body.length }));
