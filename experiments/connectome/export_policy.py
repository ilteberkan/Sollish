"""Generate bounded standalone TypeScript inference only for an accepted artifact."""
import argparse
import hashlib
import json
import math
from pathlib import Path

TEMPLATE = '''/** GENERATED by experiments/connectome/export_policy.py; do not hand-edit weights.
 * Real MaleCNS v1.0 descending-neuron subset, CC BY 4.0: https://male-cns.janelia.org/download/
 * Attribution: FlyEM/HHMI Janelia, Cambridge, MRC LMB, Google Research.
 * Fixed assumed reservoir + learned synthetic-teacher readout. Not a whole brain,
 * biological simulation, self-play policy, consciousness, or financial readiness.
 * No clock, RNG, network, wagers, identities or balances are accepted.
 */
export const CONNECTOME_ACTIONS = ['advance','circle','guard','slip','jab','cross','hook','kick'] as const;
export type ConnectomeAction = typeof CONNECTOME_ACTIONS[number];
export const CONNECTOME_POLICY_INFO = Object.freeze(__INFO__);
const MODEL = __MODEL__;
const NODE_COUNT = 128;
const INPUT_COUNT = 10;
const HIDDEN_COUNT = 32;

export function createPolicyState(): Float64Array {
  return new Float64Array(NODE_COUNT);
}

/** One observation step. Each fighter owns a distinct state, reset for each match.
 * Returns logits, NOT calibrated odds/probabilities. Legal actions remain an engine rule.
 * Invalid input/state fails before mutation. Math.tanh parity was measured locally;
 * cross-architecture bit-exact floating-point execution is not claimed.
 */
export function evaluateCombatPolicy(inputs: readonly number[], state: Float64Array): Readonly<{action: ConnectomeAction; scores: readonly number[]}> {
  if (!Array.isArray(inputs) || inputs.length !== INPUT_COUNT ||
      !inputs.every(value => typeof value === 'number' && Number.isFinite(value) && value >= -1 && value <= 1)) {
    throw new TypeError('POLICY_INPUT_INVALID');
  }
  if (!(state instanceof Float64Array) || state.length !== NODE_COUNT ||
      !state.every(value => Number.isFinite(value) && value >= -1 && value <= 1)) {
    throw new TypeError('POLICY_STATE_INVALID');
  }
  const incoming = new Float64Array(NODE_COUNT);
  for (let edge = 0; edge < MODEL.pre.length; edge++) {
    incoming[MODEL.post[edge]] += MODEL.weights[edge] * state[MODEL.pre[edge]];
  }
  const next = new Float64Array(NODE_COUNT);
  for (let node = 0; node < NODE_COUNT; node++) {
    const row = MODEL.inputWeights[node];
    let drive = row[0];
    for (let input = 0; input < INPUT_COUNT; input++) drive += row[input + 1] * inputs[input];
    next[node] = (1 - MODEL.leak) * state[node] + MODEL.leak * Math.tanh(drive + incoming[node]);
  }
  const feature = [1, ...inputs, ...next];
  for (let i = 0; i < feature.length; i++) feature[i] = (feature[i] - MODEL.head.mean[i]) / MODEL.head.scale[i];
  const hidden = new Float64Array(HIDDEN_COUNT);
  for (let j = 0; j < HIDDEN_COUNT; j++) {
    let value = MODEL.head.b1[j];
    for (let i = 0; i < feature.length; i++) value += feature[i] * MODEL.head.w1[i][j];
    hidden[j] = Math.max(0, value);
  }
  const scores = new Array<number>(8);
  for (let action = 0; action < 8; action++) {
    let value = MODEL.head.b2[action];
    for (let j = 0; j < HIDDEN_COUNT; j++) value += hidden[j] * MODEL.head.w2[j][action];
    scores[action] = value;
  }
  if (!scores.every(Number.isFinite) || !next.every(Number.isFinite)) throw new TypeError('POLICY_NUMERICS_INVALID');
  let selected = 0;
  for (let action = 1; action < 8; action++) if (scores[action] > scores[selected]) selected = action;
  state.set(next);
  return { action: CONNECTOME_ACTIONS[selected], scores };
}

export function chooseCombatAction(inputs: readonly number[], state: Float64Array): ConnectomeAction {
  return evaluateCombatPolicy(inputs, state).action;
}
'''


def export(model_path: Path, report_path: Path, output_path: Path):
    model = json.loads(model_path.read_text())
    report = json.loads(report_path.read_text())
    digest = hashlib.sha256(json.dumps(model, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()
    if digest != report["modelSha256"] or report["acceptance"]["passed"] is not True:
        raise ValueError("MODEL_NOT_ACCEPTED_OR_HASH_MISMATCH")
    if model["schemaVersion"] != 2 or len(model["nodeIds"]) != 128 or len(model["pre"]) > 16_384:
        raise ValueError("MODEL_SHAPE")
    def vector(value, length, bound=1_000_000):
        return isinstance(value,list) and len(value)==length and all(type(x) in (int,float) and math.isfinite(x) and abs(x)<=bound for x in value)
    def matrix(value, rows, columns, bound=1_000_000):
        return isinstance(value,list) and len(value)==rows and all(vector(row,columns,bound) for row in value)
    edge_count=len(model["pre"])
    if not (0 < edge_count <= 16_384 and len(model["post"])==edge_count and
            all(type(x) is int and 0<=x<128 for x in model["pre"]+model["post"]) and
            vector(model["weights"],edge_count,1) and all(x>0 for x in model["weights"]) and
            matrix(model["inputWeights"],128,11,1) and type(model["leak"]) in (int,float) and 0<model["leak"]<=1):
        raise ValueError("RESERVOIR_SHAPE")
    head=model["head"]
    if not (vector(head["mean"],139) and vector(head["scale"],139) and min(head["scale"])>=.1 and
            matrix(head["w1"],139,32) and vector(head["b1"],32) and matrix(head["w2"],32,8) and vector(head["b2"],8)):
        raise ValueError("READOUT_SHAPE")
    if model["actions"] != ["advance","circle","guard","slip","jab","cross","hook","kick"]:
        raise ValueError("ACTION_SCHEMA")
    info = {"version": model["version"], "modelSha256": digest, "graphSha256": model["graphSha256"], "source": "male-cns:v1.0", "license": "CC-BY-4.0", "nodes":128,"edges":len(model["pre"]), "learnedReadout":True,"wholeBrain":False,"selfPlayTrained":False,"biologicalDynamicsValidated":False,"financialReadiness":False}
    # Runtime carries only inference arrays; full provenance remains in the artifact.
    runtime = {key: model[key] for key in ("pre","post","weights","inputWeights","head","leak")}
    text = TEMPLATE.replace('__INFO__',json.dumps(info,separators=(',',':'))).replace('__MODEL__',json.dumps(runtime,separators=(',',':'),allow_nan=False))
    output_path.write_text(text)
    print(json.dumps({"modelSha256":digest,"outputBytes":len(text.encode()),"outputSha256":hashlib.sha256(text.encode()).hexdigest()}))


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model",type=Path);parser.add_argument("report",type=Path);parser.add_argument("output",type=Path)
    args=parser.parse_args();export(args.model,args.report,args.output)
