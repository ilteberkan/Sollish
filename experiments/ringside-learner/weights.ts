// Writes packages/protocol/src/contact-v5-weights.ts: the frozen initial readout weights of the Contact 5
// learner. The engine id ends with the first 8 hex of a hash over the weights, the learning rule, the
// reward table, the reservoir, the tempo rules and the plan cadence, so any change to them yields a new engine id.
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { LEARNER_RULE, LEARNER_INFO, LEARNER_ACTIONS, LEARNER_INPUT_NAMES, type LearnerParams } from '../../packages/protocol/src/contact-learner';
import { V5_FIGHTERS, V5_TEMPO, V5_KICK_RULES, V5_MODEL } from '../../packages/protocol/src/combat-v5';
import { V5_STRIKES } from '../../packages/protocol/src/combat-v5-strikes';
import { PLAN_COUNT, PLAN_TICKS, PLAN_WINDOW_TICKS } from '../../packages/protocol/src/corner-plan';

export const V5_REWARD_TABLE = { dealt: 0.01, taken: -0.01, blocked: -0.02, dodged: -0.06, dodge: 0.06, miss: -0.04, knockdown: 2, knocked: -2, adherence: 0.03 };
export const V5_CLINCH_COOLDOWN_TICKS = 100;
const round7 = (x: number) => { const v = Number(x.toFixed(7)); return Object.is(v, -0) ? 0 : v; };

/** Hash of everything the engine id covers; the engine id ends with its first 8 hex. */
export function engineSha(params: LearnerParams) {
  const stored = { actor: params.actor.map(round7), critic: params.critic.map(round7) };
  const identity = JSON.stringify({ params: stored, rule: LEARNER_RULE, reward: V5_REWARD_TABLE, clinchCooldown: V5_CLINCH_COOLDOWN_TICKS, fighters: V5_FIGHTERS, learner: LEARNER_INFO, names: { actions: LEARNER_ACTIONS, inputs: LEARNER_INPUT_NAMES }, strikes: V5_STRIKES, kickRules: V5_KICK_RULES, model: V5_MODEL, tempo: V5_TEMPO, plans: { ticks: PLAN_TICKS, count: PLAN_COUNT, window: PLAN_WINDOW_TICKS } });
  return { stored, sha: createHash('sha256').update(identity).digest('hex') };
}

/** `trained: false` writes an untrained placeholder (all-zero readout, uniform policy) that only keeps the engine runnable
 * until a real checkpoint is frozen; tests use CONTACT_V5_TRAINED to skip band checks that need a trained policy. */
export function writeWeights(params: LearnerParams, provenance: Record<string, unknown>, path = 'packages/protocol/src/contact-v5-weights.ts', trained = true) {
  const { stored, sha } = engineSha(params);
  writeFileSync(path, `/** GENERATED by experiments/ringside-learner (weights.ts); do not hand-edit.
 * Frozen initial readout weights of the Contact 5 in-match learner. Inside a match they change only
 * through contact-learner.ts. Provenance: ${JSON.stringify(provenance)}
 */
import type { LearnerParams } from './contact-learner';
export const COMBAT_V5_VERSION = 'ringside-contact-5-${sha.slice(0, 8)}' as const;
export const CONTACT_V5_WEIGHTS_SHA = '${sha}';
/** false = untrained placeholder (all-zero readout); the orchestrator replaces it by freezing a trained checkpoint. */
export const CONTACT_V5_TRAINED = ${trained};
export const CONTACT_V5_PARAMS: LearnerParams = ${JSON.stringify(stored)};
`);
  return sha;
}
