// Copies the fixed MaleCNS descending-neuron reservoir (graph only, no trained readout) out of the
// frozen Contact 4 policy module into its own generated module for Contact 5. The v4 file is read,
// never modified. Run: node experiments/ringside-learner/export-reservoir.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const source = readFileSync('packages/protocol/src/connectome-policy.ts', 'utf8');
const model = JSON.parse(source.match(/const MODEL = (\{.*\});\n/)[1]);
const info = JSON.parse(source.match(/CONNECTOME_POLICY_INFO = Object\.freeze\((\{.*?\})\);/)[1]);
const graph = { nodes: 128, leak: model.leak, pre: model.pre, post: model.post, weights: model.weights };
const body = JSON.stringify(graph);
const sha = createHash('sha256').update(body).digest('hex');
writeFileSync('packages/protocol/src/connectome-reservoir.ts', `/** GENERATED by experiments/ringside-learner/export-reservoir.mjs; do not hand-edit.
 * Fixed recurrent graph of the MaleCNS v1.0 descending-neuron subset (128 nodes, ${model.pre.length} directed
 * edges, each target's incoming weight normalized to 0.8), copied from the Contact 4 policy without its
 * trained readout. CC BY 4.0, https://male-cns.janelia.org/download/ ; attribution: FlyEM/HHMI Janelia,
 * Cambridge, MRC LMB, Google Research. Source graph sha256 ${info.graphSha256}.
 * Not a whole brain, not calibrated neurons, not a transferred mind. All edges are positive (no
 * transmitter sign was inferred). The learning lives in contact-learner.ts, not in these weights.
 */
export const RESERVOIR_INFO = Object.freeze({ source: 'male-cns:v1.0', license: 'CC-BY-4.0', graphSha256: '${info.graphSha256}', reservoirSha256: '${sha}', nodes: 128, edges: ${model.pre.length} });
export const RESERVOIR: Readonly<{ nodes: number; leak: number; pre: readonly number[]; post: readonly number[]; weights: readonly number[] }> = ${body};
`);
console.log(JSON.stringify({ reservoirSha256: sha, edges: model.pre.length }));
