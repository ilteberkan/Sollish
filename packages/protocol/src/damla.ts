export interface DamlaRound {
  engine: typeof DAMLA_ENGINE_ID; seedHex: string; mode: DamlaMode; risk: DamlaRisk; rows: DamlaRows; betCents: number; costCents: number;
  /** One decision per terrace, top first. */
  path: ("L" | "R")[];
  /** Number of right spills = pool index. */
  slot: number;
  multiplierHundredths: number; totalHundredths: number; payoutCents: number;
  /** True only when the pool is the mode cap (its largest pool). */
  capped: boolean;
  freeSpinsTriggered: false;
}

const SEED_PATTERN = /^[0-9a-f]{32}$/;
const BET_LEVELS = new Set<number>(DAMLA_BET_LEVELS_CENTS);
function splitMix32(seed: number): () => number {
  let a = seed | 0;
  return () => {
    a = (a + 0x9e3779b9) | 0;
    let t = a ^ (a >>> 16);
    t = Math.imul(t, 0x21f0aaad);
    t ^= t >>> 15;
    t = Math.imul(t, 0x735a2d97);
    return (t ^ (t >>> 15)) >>> 0;
  };
}
const rotl = (x: number, k: number): number => ((x << k) | (x >>> (32 - k))) >>> 0;
function createRng(seedHex: string): () => number {
  const words = [0, 1, 2, 3].map(i => parseInt(seedHex.slice(i * 8, i * 8 + 8), 16) >>> 0);
  const fold = (words[0]! ^ rotl(words[1]!, 8) ^ rotl(words[2]!, 16) ^ rotl(words[3]!, 24)) >>> 0;
  const expand = splitMix32(fold);
  let s0 = (expand() ^ words[0]!) >>> 0, s1 = (expand() ^ words[1]!) >>> 0;
  let s2 = (expand() ^ words[2]!) >>> 0, s3 = (expand() ^ words[3]!) >>> 0;
  if ((s0 | s1 | s2 | s3) === 0) s0 = 0x9e3779b9;
  const next = (): number => {
    const result = Math.imul(rotl(Math.imul(s1, 5) >>> 0, 7), 9) >>> 0;
    const t = (s1 << 9) >>> 0;
    s2 = (s2 ^ s0) >>> 0; s3 = (s3 ^ s1) >>> 0; s1 = (s1 ^ s2) >>> 0; s0 = (s0 ^ s3) >>> 0;
    s2 = (s2 ^ t) >>> 0; s3 = rotl(s3, 11);
    return result;
  };
  for (let i = 0; i < 8; i++) next(); // discard the first outputs while the state diffuses
  return next;
}

function validate(seedHex: unknown, betCents: unknown, mode: unknown): asserts seedHex is string {
  if (typeof seedHex !== "string" || !SEED_PATTERN.test(seedHex)) throw new RangeError("seedHex must be 32 lowercase hex characters");
  if (typeof betCents !== "number" || !BET_LEVELS.has(betCents)) throw new RangeError("betCents must be one of DAMLA_BET_LEVELS_CENTS");
  if (typeof mode !== "string" || !(DAMLA_MODES as readonly string[]).includes(mode)) throw new RangeError("mode must be <low|medium|high>-<8|10|12|14|16>");
}

/** Cost in cents of one round (= the bet). Throws RangeError for a bet outside DAMLA_BET_LEVELS_CENTS or an unknown mode. */
export function damlaCostCents(betCents: number, mode: DamlaMode): number {
  validate("0".repeat(32), betCents, mode);
  return betCents;
}

/** Resolves a whole round: the drop's path over the terraces, the pool, the multiplier and the integer payout.
 * Throws RangeError for a seed that is not 32 lowercase hex characters, a bet outside the levels or an unknown mode. */
export function playDamlaRound(seedHex: string, betCents: number, mode: DamlaMode): DamlaRound {
  validate(seedHex, betCents, mode);
  const [risk, rowsText] = mode.split("-") as [DamlaRisk, string], rows = Number(rowsText) as DamlaRows;
  const rng = createRng(seedHex), path: ("L" | "R")[] = [];
  let slot = 0;
  for (let i = 0; i < rows; i++) { if (rng() >= 0x80000000) { path.push("R"); slot++; } else path.push("L"); }
  const multiplierHundredths = DAMLA_PAYTABLES[mode]![slot]!;
  return {
    engine: DAMLA_ENGINE_ID, seedHex, mode, risk, rows, betCents, costCents: betCents, path, slot,
    multiplierHundredths, totalHundredths: multiplierHundredths, payoutCents: Number(BigInt(betCents) * BigInt(multiplierHundredths) / 100n),
    capped: multiplierHundredths === CAPS[mode], freeSpinsTriggered: false,
  };
}

/** 4 x uint32 (for example crypto.getRandomValues) -> 32 lowercase hex characters, word 0 first. */
export function damlaSeedFromEntropy(words: Uint32Array): string {
  if (!(words instanceof Uint32Array) || words.length !== 4) throw new RangeError("Entropy must be a Uint32Array of 4 words");
  let out = "";
  for (let i = 0; i < 4; i++) out += (words[i]! >>> 0).toString(16).padStart(8, "0");
  return out;
}

