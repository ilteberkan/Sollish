function binomial(n: number, k: number): bigint { let r = 1n; for (let i = 1; i <= k; i++) r = (r * BigInt(n - k + i)) / BigInt(i); return r; }
/** Exact RTP of a mode as a ratio (binomial sum with BigInt, rounded down to 9 decimals). */
function exactRtp(mode: DamlaMode): number {
  const rows = Number(mode.split("-")[1]), table = DAMLA_PAYTABLES[mode]!;
  let num = 0n;
  for (let k = 0; k <= rows; k++) num += binomial(rows, k) * BigInt(table[k]!);
  return Number(num * 1_000_000_000n / (100n * (1n << BigInt(rows)))) / 1e9;
}
