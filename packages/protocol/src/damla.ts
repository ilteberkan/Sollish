/** Damla: Pamukkale engine `damla-terraces-1` (Sollish Original): a one-drop Plinko-style game. DEMO-credit only.
 * Pure and deterministic: same 32-hex seed, bet level and mode always give the identical round. No clock, no Math.random, no
 * network, no balance or wager input beyond the bet level. The whole round is resolved before presentation; animation, tab
 * visibility, reduced motion or disconnects cannot change a result. All arithmetic is integer: the multiplier is in hundredths
 * of the BET and the payout is floor(betCents * hundredths / 100). Authoritative rules: docs/product/games-wave3.md section 2.
 *
 * Rules: one water drop falls over R terraces (R = 8, 10, 12, 14 or 16). On every terrace it spills over the left or the right rim,
 * each with probability 1/2. k = number of right spills (0..R) picks the pool; the pool pays DAMLA_PAYTABLES[mode][k] / 100 x bet.
 * Mode = `<risk>-<rows>`, risk low | medium | high: 15 modes. Cost of a round = bet (no ante, no buy). No free spins.
 *
 * RNG and draw order: SplitMix32 expands the seed into xoshiro128** (same construction as asena.ts). One u32 per terrace in order
 * from the top terrace down; the terrace spills right when the u32 is >= 2^31 (top bit set), else left.
 *
 * Paytable formula (original; generated by experiments/damla/generate.ts, verified exactly by experiments/damla/exact.ts):
 * d = |k - R/2| / (R/2) in [0, 1] is the distance of the pool from the centre. pool(k) = round(C + (E - C) * d^p) hundredths, where
 *   C = centre floor  (low 0.50x, medium 0.30x, high 0.20x),
 *   E = edge multiplier per risk and rows (low 5.6, 8, 10, 13, 16; medium 13, 22, 33, 55, 110; high 26, 60, 140, 360, 1000),
 *   p = exponent solved per mode by bisection so that the exact binomial RTP is 98.5 percent.
 * Every pool is rounded to a whole hundredth and the four innermost rings are nudged by +-1 hundredth (monotone, centre floor
 * kept) to bring the exact RTP as close to 98.5 percent as integers allow. Tables are symmetric and non-decreasing from the
 * centre out. The cap of a mode is its largest pool (the edge); DAMLA_MAX_WIN_MULTIPLIER is the largest cap (high-16 = 1000 x).
 */

